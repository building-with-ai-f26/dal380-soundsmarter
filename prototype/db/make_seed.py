"""Turns the prompt CSV into SQL that loads (or updates) the prompts table.

The CSV in design/ is the source of truth; the database copy is rebuilt from
it. Re-run after every approval change, then paste the output into each
Supabase project's SQL Editor (dev first, then prod):

  cd prototype && uv run python db/make_seed.py && pbcopy < db/seed/prompts.sql

Only rows with status 'approved' are ever served (RLS); drafts are loaded too
so ids stay stable.
"""

import csv
from pathlib import Path

HERE = Path(__file__).parent
REPO = HERE.parent.parent
TEXT_CSV = REPO / "design" / "2026-11-21-prompts-text-draft.csv"
OUT = HERE / "seed" / "prompts.sql"
COLUMNS = ["id", "family", "mode", "variant", "openness", "beats", "words_on_screen", "stimulus_id", "text", "status"]


def sql_value(col: str, v: str) -> str:
    if v == "":
        return "null"
    if col in ("beats", "words_on_screen"):
        return str(int(v))
    return "'" + v.replace("'", "''") + "'"  # SQL escapes a quote by doubling it


def build(rows: list[dict]) -> str:
    values = ",\n".join("  (" + ", ".join(sql_value(c, r[c]) for c in COLUMNS) + ")" for r in rows)
    updates = ", ".join(f"{c} = excluded.{c}" for c in COLUMNS if c != "id")
    return (
        f"-- Generated by db/make_seed.py from {TEXT_CSV.name}. Do not edit by hand.\n"
        f"-- {len(rows)} prompts, {sum(r['status'] == 'approved' for r in rows)} approved.\n"
        f"insert into public.prompts ({', '.join(COLUMNS)}) values\n{values}\n"
        f"on conflict (id) do update set {updates};\n"
    )


def main():
    rows = list(csv.DictReader(TEXT_CSV.open()))
    OUT.write_text(build(rows))
    print(f"wrote {OUT.relative_to(REPO)}: {len(rows)} prompts, {sum(r['status'] == 'approved' for r in rows)} approved")


if __name__ == "__main__":
    main()
