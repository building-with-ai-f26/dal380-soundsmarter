"""Turns the prompt and stimulus CSVs into SQL that loads (or updates) the database.

The CSVs in design/ are the source of truth; the database copy is rebuilt from
them. Re-run after every approval change, then paste the output into each
Supabase project's SQL Editor (dev first, then prod):

  cd prototype && uv run python db/make_seed.py && pbcopy < db/seed/prompts.sql

Only rows with status 'approved' are ever served (RLS); drafts are loaded too
so ids stay stable. Pasting it sets every row's status to what the CSV says.

Stimuli (image files) are loaded before prompts, because an image prompt points
at its stimulus. In the stimulus CSV, `files` lists the file names in the
'stimuli' Storage bucket, separated by | (one for a scene, two for a pair).
"""

import csv
from pathlib import Path

HERE = Path(__file__).parent
REPO = HERE.parent.parent
TEXT_CSV = REPO / "design" / "2026-11-21-prompts-text-draft.csv"
IMAGE_CSV = REPO / "design" / "2026-11-22-prompts-image.csv"
STIMULI_CSV = REPO / "design" / "2026-11-22-stimuli-image.csv"
OUT = HERE / "seed" / "prompts.sql"
PROMPT_COLUMNS = ["id", "family", "mode", "variant", "openness", "beats", "words_on_screen", "stimulus_id", "text", "status"]
STIMULUS_COLUMNS = ["id", "kind", "files", "title", "creator", "year", "source_url", "license", "credit", "status"]


def quote(v: str) -> str:
    return "'" + v.replace("'", "''") + "'"  # SQL escapes a quote by doubling it


def sql_value(col: str, v: str) -> str:
    if col == "files":  # 'a.jpg|b.jpg' -> a list of file names
        return "array[" + ", ".join(quote(f) for f in v.split("|") if f) + "]::text[]"
    if col == "text":   # an image prompt has no text of its own; the column can't be empty-as-null
        return quote(v)
    if v == "":
        return "null"
    if col in ("beats", "words_on_screen"):
        return str(int(v))
    return quote(v)


def upsert(table: str, columns: list[str], rows: list[dict]) -> str:
    values = ",\n".join("  (" + ", ".join(sql_value(c, r[c]) for c in columns) + ")" for r in rows)
    updates = ", ".join(f"{c} = excluded.{c}" for c in columns if c != "id")
    return (f"insert into public.{table} ({', '.join(columns)}) values\n{values}\n"
            f"on conflict (id) do update set {updates};\n")


def build(prompts: list[dict], stimuli: list[dict]) -> str:
    approved = sum(r["status"] == "approved" for r in prompts)
    return (
        f"-- Generated by db/make_seed.py from {TEXT_CSV.name}, {IMAGE_CSV.name} and {STIMULI_CSV.name}. Do not edit by hand.\n"
        f"-- {len(stimuli)} stimuli, {sum(r['status'] == 'approved' for r in stimuli)} approved. "
        f"{len(prompts)} prompts, {approved} approved.\n"
        + upsert("stimuli", STIMULUS_COLUMNS, stimuli) + "\n"
        + upsert("prompts", PROMPT_COLUMNS, prompts)
    )


def main():
    prompts = list(csv.DictReader(TEXT_CSV.open())) + list(csv.DictReader(IMAGE_CSV.open()))
    stimuli = list(csv.DictReader(STIMULI_CSV.open()))
    OUT.write_text(build(prompts, stimuli))
    print(f"wrote {OUT.relative_to(REPO)}: {len(stimuli)} stimuli, {len(prompts)} prompts, "
          f"{sum(r['status'] == 'approved' for r in prompts)} approved")


if __name__ == "__main__":
    main()
